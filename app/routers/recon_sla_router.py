# SLA refresh
# -------------------------------------------------------------------


@router.post("/sla/refresh")
async def refresh_sla(
    hours: int = Query(48, ge=1, le=168),
    db: AsyncSession = Depends(get_db),
    current_user: Any = Depends(get_current_user),
):
    """
    Recompute SLA fields for open (unmatched) items:

    - Backfills sla_hours / opened_at / sla_due_at if missing.
    - Normalizes datetimes to naive UTC.
    - Marks sla_breached=True when now > sla_due_at.

    Returns summary:
    {
      "checked": ...,
      "updated": ...,
      "newly_breached": ...,
      "run_at": "..."
    }
    """
    result = await refresh_sla_for_open_items(
        db=db,
        default_sla_hours=hours,
    )
    return result


