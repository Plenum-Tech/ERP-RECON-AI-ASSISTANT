@router.get("/digest/daily")
async def get_daily_digest(
    owner_id: Optional[str] = Query(None),
    window_days: int = Query(1, ge=1, le=30),
    db: AsyncSession = Depends(get_db),
    current_user: Any = Depends(get_current_user),
):
    """
    Build a daily-style digest over unmatched recon items.

    - window_days: how many days back from now (based on opened_at).
    - owner_id (optional): filter by owner; if omitted, includes all owners.

    Returns a ReconDigest schema:
    - unmatched_count
    - avg_age_days
    - sla_breached_count
    - unmatched_by_variance_type
    - items: [ { id, tx_id, employee_id, owner_id, variance_type, ... } ]
    """
    digest = await compute_recon_digest(
        db=db,
        owner_id=owner_id,
        window_days=window_days,
    )
    return digest


# -------------------------------------------------------------------
# Daily digest email sender
# -------------------------------------------------------------------


@router.post("/digest/email/send")
async def send_daily_digest_email(
    body: DigestEmailRequest,
    db: AsyncSession = Depends(get_db),
    current_user: Any = Depends(get_current_user),
):
    """
    Compute the recon daily digest and send it as an HTML email.

    Request body:
    - to_email: recipient email
    - owner_id (optional): filter items by owner
    - window_days: how many days back to include (based on opened_at)

    Returns:
    {
      "email": { ... email send result ... },
      "digest_summary": {
          "owner_id": ...,
          "window_days": ...,
          "unmatched_count": ...,
          "avg_age_days": ...,
          "sla_breached_count": ...
      }
    }
    """
    digest = await compute_recon_digest(
        db=db,
        owner_id=body.owner_id,
        window_days=body.window_days,
    )

    subject_owner = body.owner_id or "All owners"
    subject_date = digest.as_of.date().isoformat() if digest.as_of else ""
    subject = f"Recon digest – {subject_owner} – {subject_date}"

    html_body = _render_digest_email_html(digest)

    email_result = await send_email(
        to_email=body.to_email,
        subject=subject,
        html_body=html_body,
    )

    return {
        "email": email_result,
        "digest_summary": {
            "owner_id": digest.owner_id,
            "window_days": digest.window_days,
            "unmatched_count": digest.unmatched_count,
            "avg_age_days": digest.avg_age_days,
            "sla_breached_count": digest.sla_breached_count,
        },
    }
