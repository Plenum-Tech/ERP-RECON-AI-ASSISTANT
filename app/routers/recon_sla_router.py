class DigestEmailRequest(BaseModel):
    to_email: str
    owner_id: Optional[str] = None
    window_days: int = Field(
        1,
        ge=1,
        le=30,
        description="How many days back to include unmatched items based on opened_at",
    )


# -------------------------------------------------------------------
# Helper to render HTML email from ReconDigest
# -------------------------------------------------------------------


def _render_digest_email_html(digest: ReconDigest) -> str:
    """Render a simple HTML email for the recon daily digest."""
    as_of_str = digest.as_of.strftime("%Y-%m-%d %H:%M:%S") if digest.as_of else ""
    owner_label = digest.owner_id or "All owners"

    # limit items in email to avoid huge emails
    max_items = 20
    items = digest.items[:max_items] if digest.items else []

    rows_html = ""
    for item in items:
        rows_html += f"""
        <tr>
          <td>{item.id}</td>
          <td>{item.tx_id}</td>
          <td>{item.employee_id or ""}</td>
          <td>{item.owner_id or ""}</td>
          <td>{item.variance_type or ""}</td>
          <td>{item.variance_amount or ""}</td>
          <td>{item.match_status}</td>
          <td>{item.sla_breached}</td>
          <td>{item.age_days:.2f}</td>
        </tr>
        """

    html = f"""
    <html>
      <body>
        <h2>Recon Daily Digest – {owner_label}</h2>
        <p><b>As of:</b> {as_of_str}</p>
        <p><b>Window (days):</b> {digest.window_days}</p>
        <hr />
        <p>
          <b>Unmatched items:</b> {digest.unmatched_count}<br/>
          <b>Average age (days):</b> {digest.avg_age_days:.2f}<br/>
          <b>SLA-breached items:</b> {digest.sla_breached_count}
        </p>

        <h3>Unmatched by variance type</h3>
        <ul>
    """
    for vtype, count in (digest.unmatched_by_variance_type or {}).items():
        html += f"<li>{vtype}: {count}</li>"

    html += f"""
        </ul>

        <h3>Items (top {max_items})</h3>
        <table border="1" cellspacing="0" cellpadding="4">
          <thead>
            <tr>
              <th>Item ID</th>
              <th>Tx ID</th>
              <th>Employee</th>
              <th>Owner</th>
              <th>Variance Type</th>
              <th>Variance Amount</th>
              <th>Status</th>
              <th>SLA Breached</th>
              <th>Age (days)</th>
            </tr>
          </thead>
          <tbody>
            {rows_html}
          </tbody>
        </table>

        <p style="margin-top:20px; font-size: 12px; color:#777;">
          This is an automated recon digest generated by the Recon Insight engine.
        </p>
      </body>
    </html>
    """

    return html


